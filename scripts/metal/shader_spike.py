def _artifact_hashes(results: list[dict[str, object]]) -> dict[str, dict[str, str]]:
    hashes: dict[str, dict[str, str]] = {}
    for result in results:
        program_hashes: dict[str, str] = {}
        stages = result.get("stages")
        if not isinstance(stages, dict):
            raise TypeError("program result has no stages for reproducibility")
        for stage in STAGE_SUFFIX:
            stage_result = stages.get(stage)
            if not isinstance(stage_result, dict):
                raise TypeError("program stage result is invalid")
            for artifact in ("spirv", "msl", "air"):
                value = stage_result.get(f"{artifact}_sha256")
                if not isinstance(value, str):
                    raise TypeError(f"missing {stage} {artifact} hash")
                program_hashes[f"{stage}.{artifact}"] = value
        metallib = result.get("metallib_sha256")
        if not isinstance(metallib, str):
            raise TypeError("missing metallib hash")
        program_hashes["metallib"] = metallib
        hashes[str(result["id"])] = program_hashes
    return hashes


def _mutate_first_mat4(
    value: object,
    field: str,
    replacement: object,
    drop_layout_metadata: bool = False,
) -> bool:
    if isinstance(value, dict):
        if (
            value.get("type") == "mat4"
            and value.get("matrix_stride") == 16
            and value.get("matrix_major") == "column"
        ):
            value[field] = replacement
            if drop_layout_metadata:
                value.pop("matrix_stride", None)
                value.pop("matrix_major", None)
            return True
        return any(
            _mutate_first_mat4(item, field, replacement, drop_layout_metadata)
            for item in value.values()
        )
    if isinstance(value, list):
        return any(
            _mutate_first_mat4(item, field, replacement, drop_layout_metadata)
            for item in value
        )
    return False


def build_runtime_artifacts(
    programs: list[ProgramRecipe],
    results: list[dict[str, object]],
    output_root: Path,
    pipeline_validator: Path,
) -> dict[str, object]:
    """Link and validate the representative runtime-only artifact set."""

    runtime_recipes = sorted(
        (recipe for recipe in programs if recipe.recipe_kind in BUNDLED_RECIPE_KINDS),
        key=lambda recipe: recipe.program_id,
    )
    if {
        recipe.program_id for recipe in runtime_recipes
    } != REQUIRED_BUNDLED_PROGRAM_IDS or len(
        {item.family for item in runtime_recipes}
    ) != 10:
        raise RuntimeProgramError(
            "runtime artifact requires the exact 28 bundled recipes across 10 families"
        )
    by_id = {str(result.get("id")): result for result in results}
    if len(by_id) != len(results):
        raise RuntimeProgramError("translation results contain duplicate program IDs")

    artifact_root = output_root / ARTIFACT_BASENAME
    artifact_root.mkdir(exist_ok=True)
    metallib_path = artifact_root / f"{ARTIFACT_BASENAME}.metallib"
    ordered_air: list[Path] = []
    for recipe in runtime_recipes:
        result = by_id.get(recipe.program_id)
        if result is None or not result.get("metal_pipeline_passed"):
            raise RuntimeProgramError(
                f"runtime recipe did not pass before aggregation: {recipe.program_id}"
            )
        stages = result.get("stages")
        if not isinstance(stages, dict):
            raise RuntimeProgramError(f"{recipe.program_id} has no stage results")
        for stage in ("vertex", "fragment"):
            stage_result = stages.get(stage)
            air = stage_result.get("air") if isinstance(stage_result, dict) else None
            if not isinstance(air, str):
                raise RuntimeProgramError(
                    f"{recipe.program_id}.{stage} has no compiled AIR"
                )
            air_path = output_root / air
            if not air_path.is_file():
                raise RuntimeProgramError(f"{recipe.program_id}.{stage} AIR is missing")
            ordered_air.append(air_path)

    link_result = _run(
        [
            str(SYSTEM_XCRUN),
            "-sdk",
            "macosx",
            "metallib",
            *(os.path.relpath(path, artifact_root) for path in ordered_air),
            "-o",
            metallib_path.name,
        ],
        cwd=artifact_root,
    )
    if link_result.returncode != 0:
        raise RuntimeProgramError(
            "cannot link the declared program metallib: "
            + _combined_output(link_result)
        )

    records: list[dict[str, object]] = []
    pipeline_specs: list[tuple[str, dict[str, object]]] = []
    for recipe in runtime_recipes:
        result = by_id[recipe.program_id]
        spec_relative = result.get("pipeline_spec")
        stages = result.get("stages")
        if not isinstance(spec_relative, str) or not isinstance(stages, dict):
            raise RuntimeProgramError(
                f"{recipe.program_id} has no validated pipeline specification"
            )
        try:
            spec_value = json.loads(
                (output_root / spec_relative).read_text(encoding="utf-8")
            )
        except (OSError, json.JSONDecodeError) as error:
            raise RuntimeProgramError(
                f"cannot read {recipe.program_id} pipeline specification: {error}"
            ) from error
        if not isinstance(spec_value, dict):
            raise RuntimeProgramError(
                f"{recipe.program_id} pipeline specification is not an object"
            )
        reflections: dict[str, dict[str, object]] = {}
        for stage in ("vertex", "fragment"):
            stage_result = stages.get(stage)
            reflection = (
                stage_result.get("reflection")
                if isinstance(stage_result, dict)
                else None
            )
            if not isinstance(reflection, str):
                raise RuntimeProgramError(
                    f"{recipe.program_id}.{stage} reflection is missing"
                )
            reflections[stage] = _load_reflection(output_root / reflection)
        record = make_program_record(recipe.family, spec_value, reflections)
        records.append(record)
        pipeline_specs.append((recipe.program_id, spec_value))

    try:
        manifest_document = json.loads(
            runtime_recipes[0].input_snapshot.manifest_bytes.decode("utf-8")
        )
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise RuntimeProgramError(
            f"cannot identify the source manifest: {error}"
        ) from error
    if not isinstance(manifest_document, dict):
        raise RuntimeProgramError("source manifest identity is not an object")
    document = make_artifact_document(
        records,
        _sha256(metallib_path),
        manifest_document.get("schema"),
        runtime_recipes[0].input_snapshot.digest(
            runtime_recipes[0].input_snapshot.manifest_path
        ),
        runtime_recipes[0].baseline_commit,
    )
    json_path = artifact_root / f"{ARTIFACT_BASENAME}.json"
    write_json(document, json_path)
    header_path, source_path = write_cpp(document, artifact_root)

    validations: list[str] = []
    environment = dict(os.environ)
    environment["MTL_DEBUG_LAYER"] = "1"
    environment["MTL_SHADER_VALIDATION"] = "1"
    with tempfile.TemporaryDirectory(
        prefix="firestorm-metal-runtime-spec-"
    ) as directory:
        validation_root = Path(directory)
        for program_id, spec in pipeline_specs:
            transient_spec = dict(spec)
            transient_spec["metallib"] = str(metallib_path.resolve())
            spec_path = validation_root / f"{program_id}.json"
            spec_path.write_text(
                json.dumps(transient_spec, indent=2, sort_keys=True) + "\n",
                encoding="utf-8",
            )
            validation = _run(
                [str(pipeline_validator), str(spec_path)],
                environment=environment,
            )
            if validation.returncode != 0:
                raise RuntimeProgramError(
                    f"combined metallib pipeline validation failed for {program_id}: "
                    f"{_combined_output(validation)}"
                )
            validations.append(program_id)

        negative_program_id, negative_source = next(
            (
                (program_id, spec)
                for program_id, spec in pipeline_specs
                if any(spec["expected_arguments"][stage] for stage in STAGE_SUFFIX)
            ),
            (None, None),
        )
        if negative_program_id is None or negative_source is None:
            raise RuntimeProgramError(
                "no runtime binding is available for negative validation"
            )
        negative_spec = json.loads(json.dumps(negative_source))
        negative_spec["metallib"] = str(metallib_path.resolve())
        for stage in STAGE_SUFFIX:
            arguments = negative_spec["expected_arguments"][stage]
            if arguments:
                arguments[0]["metal_name"] = "wrong_native_name"
                break
        negative_path = validation_root / "wrong-native-binding-name.json"
        negative_path.write_text(
            json.dumps(negative_spec, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        negative_validation = _run(
            [str(pipeline_validator), str(negative_path)],
            environment=environment,
        )
        if (
            negative_validation.returncode == 0
            or "matched Metal name" not in _combined_output(negative_validation)
        ):
            raise RuntimeProgramError(
                "pipeline validator accepted a wrong native binding name"
            )

        matrix_source = next(
            (
                (program_id, spec)
                for program_id, spec in pipeline_specs
                if _mutate_first_mat4(
                    json.loads(json.dumps(spec)), "matrix_major", "row"
                )
            ),
            (None, None),
        )
        if matrix_source[0] is None or matrix_source[1] is None:
            raise RuntimeProgramError(
                "no canonical mat4 is available for negative validation"
            )
        matrix_program_id, matrix_spec = matrix_source
        for label, field, replacement, diagnostic, drop_layout_metadata in (
            (
                "row-major",
                "matrix_major",
                "row",
                "matrix_major must be column",
                False,
            ),
            (
                "wrong-stride",
                "matrix_stride",
                32,
                "matrix_stride must be 16",
                False,
            ),
            ("wrong-type", "type", "mat3", "expected mat3", False),
            (
                "alias-type",
                "type",
                "float4x4",
                "type is unsupported",
                True,
            ),
        ):
            mutated_spec = json.loads(json.dumps(matrix_spec))
            mutated_spec["metallib"] = str(metallib_path.resolve())
            if not _mutate_first_mat4(
                mutated_spec, field, replacement, drop_layout_metadata
            ):
                raise RuntimeProgramError(
                    f"cannot create the {label} matrix validation negative"
                )
            mutated_path = validation_root / f"matrix-{label}.json"
            mutated_path.write_text(
                json.dumps(mutated_spec, indent=2, sort_keys=True) + "\n",
                encoding="utf-8",
            )
            mutated_validation = _run(
                [str(pipeline_validator), str(mutated_path)],
                environment=environment,
            )
            if mutated_validation.returncode == 0 or diagnostic not in _combined_output(
                mutated_validation
            ):
                raise RuntimeProgramError(
                    f"pipeline validator accepted the {label} matrix mutation for "
                    f"{matrix_program_id}"
                )

    reject_embedded_paths(
        (json_path, header_path, source_path, metallib_path),
        (
            str(repository_root().resolve()),
            str(output_root.resolve()),
            "/Users/",
            "/private/",
            "indra/newview/app_settings/shaders",
            "/firestorm-metal-shader-spike/",
        ),
    )
    return {
        "passed": True,
        "program_count": len(runtime_recipes),
        "family_count": len({item.family for item in runtime_recipes}),
        "link_order": [
            f"{recipe.program_id}:{stage}"
            for recipe in runtime_recipes
            for stage in ("vertex", "fragment")
        ],
        "validated_pipelines": validations,
        "wrong_native_name_rejected": True,
        "noncanonical_matrix_layouts_rejected": True,
        "artifact_hashes": artifact_hashes(artifact_root),
    }


def verify_reproducibility(
    source_root: Path,
    programs: list[ProgramRecipe],
    primary_results: list[dict[str, object]],
    primary_runtime_artifacts: dict[str, object],
    pipeline_validator: Path,
) -> dict[str, object]:
    temporary_parent = Path(tempfile.gettempdir()).resolve()
    with tempfile.TemporaryDirectory(
        prefix="firestorm-metal-repro-", dir=temporary_parent
    ) as directory:
        second_root = Path(directory) / "second-root"
        _prepare_output(second_root)
        second_results = [
            translate_program(
                source_root,
                recipe,
                second_root,
                compile_metal=True,
                pipeline_validator=pipeline_validator,
            )
            for recipe in programs
        ]
        if not all(bool(item["metal_pipeline_passed"]) for item in second_results):
            failed = [
                str(item["id"])
                for item in second_results
                if not item["metal_pipeline_passed"]
            ]
            return {
                "passed": False,
                "reason": "second build failed",
                "programs": failed,
            }
        second_runtime_artifacts = build_runtime_artifacts(
            programs, second_results, second_root, pipeline_validator
        )
        primary_hashes = _artifact_hashes(primary_results)
        second_hashes = _artifact_hashes(second_results)
    mismatches: list[str] = []
    for program_id, artifacts in primary_hashes.items():
        for artifact, digest in artifacts.items():
            if second_hashes.get(program_id, {}).get(artifact) != digest:
                mismatches.append(f"{program_id}:{artifact}")
    primary_runtime_hashes = primary_runtime_artifacts.get("artifact_hashes")
    second_runtime_hashes = second_runtime_artifacts.get("artifact_hashes")
    if not isinstance(primary_runtime_hashes, dict) or not isinstance(
        second_runtime_hashes, dict
    ):
        raise RuntimeProgramError("runtime artifact reproducibility hashes are invalid")
    for artifact, digest in primary_runtime_hashes.items():
        if second_runtime_hashes.get(artifact) != digest:
            mismatches.append(f"declared-programs:{artifact}")
    return {
        "passed": not mismatches,
        "roots": "two distinct generated output roots",
        "compared_artifacts": sum(len(item) for item in primary_hashes.values())
        + len(primary_runtime_hashes),
        "mismatches": mismatches,
    }


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--manifest",
        type=Path,
        default=repository_root() / "doc/metal/shader-spike.json",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=repository_root() / ".build/metal-shader-spike",
    )
    parser.add_argument(
        "--validate-only",
        action="store_true",
        help="validate schema, references, and source resolution only",
    )
    parser.add_argument(
        "--skip-metal",
        action="store_true",
        help="stop after structurally mapped MSL and reflection generation",
    )
    parser.add_argument(
        "--allow-empty-output",
        action="store_true",
        help="accept an existing empty output directory created by a build system",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv or sys.argv[1:])
    try:
        source_root, programs = load_manifest(args.manifest)
        git_provenance = _capture_git_provenance(programs[0].baseline_commit)
        validate_sources(source_root, programs, git_provenance)
        inputs = programs[0].input_snapshot
        if not args.skip_metal:
            inputs.capture(
                Path(__file__).with_name("validate_metal_pipeline.mm"),
                "pipeline_validator_source",
            )
        inputs.freeze()
        if args.validate_only:
            print(f"validated {len(programs)} recipes across 10 shader families")
            return 0
        validate_tools(compile_metal=not args.skip_metal)
        _prepare_output(args.output, allow_empty=args.allow_empty_output)
        pipeline_validator = (
            None if args.skip_metal else build_pipeline_validator(args.output, inputs)
        )
    except (ManifestError, RuntimeError, OSError) as error:
        print(f"shader translation gate: {error}", file=sys.stderr)
        return 2

    try:
        results = [
            translate_program(
                source_root,
                recipe,
                args.output,
                compile_metal=not args.skip_metal,
                pipeline_validator=pipeline_validator,
            )
            for recipe in programs
        ]
        frontend_passed = all(bool(result["frontend_passed"]) for result in results)
        metal_pso_passed: bool | None = None
        runtime_artifacts: dict[str, object] = {
            "passed": None,
            "reason": "not run for the frontend-only gate",
        }
        reproducibility: dict[str, object] = {
            "passed": None,
            "reason": "not run for the frontend-only gate",
        }
        if not args.skip_metal:
            metal_pso_passed = all(
                bool(result["metal_pipeline_passed"]) for result in results
            )
            if metal_pso_passed and pipeline_validator is not None:
                runtime_artifacts = build_runtime_artifacts(
                    programs, results, args.output, pipeline_validator
                )
                reproducibility = verify_reproducibility(
                    source_root,
                    programs,
                    results,
                    runtime_artifacts,
                    pipeline_validator,
                )
            else:
                runtime_artifacts = {
                    "passed": False,
                    "reason": "not run because the primary Metal gate failed",
                }
                reproducibility = {
                    "passed": False,
                    "reason": "not run because the primary Metal gate failed",
                }
        full_gate_passed = (
            frontend_passed
            and bool(metal_pso_passed)
            and runtime_artifacts.get("passed") is True
            and reproducibility.get("passed") is True
            if not args.skip_metal
            else None
        )
        report = {
            "schema": 3,
            "scope": (
                "frontend GLSL/SPIR-V/MSL feasibility only"
                if args.skip_metal
                else "translation, reflection, real Metal PSOs, and reproducibility"
            ),
            "manifest": str(inputs.manifest_path),
            "manifest_sha256": inputs.digest(inputs.manifest_path),
            "baseline_settings": programs[0].baseline_settings,
            "resolved_shader_source_sha256": _resolved_source_hashes(programs),
            "captured_input_sha256": inputs.captured_hashes(),
            "git_provenance": git_provenance.report(),
            "metal_compilation": "skipped" if args.skip_metal else "required",
            "tool_versions": _tool_versions(compile_metal=not args.skip_metal),
            "frontend_gate_passed": frontend_passed,
            "metal_pso_gate_passed": metal_pso_passed,
            "runtime_artifact_gate": runtime_artifacts,
            "reproducibility": reproducibility,
            "full_translation_gate_passed": full_gate_passed,
            "semantic_parity_gate": "not_run",
            "mandatory_family_parity": "not_run",
            "programs": results,
        }
        report_path = args.output / "report.json"
        report_path.write_text(
            json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
    except (
        ManifestError,
        RuntimeError,
        TypeError,
        OSError,
        SpirvLocationError,
        RuntimeProgramError,
    ) as error:
        print(f"shader translation gate: {error}", file=sys.stderr)
        return 2

    passed = sum(bool(result["passed"]) for result in results)
    gate_name = "frontend shader gate" if args.skip_metal else "full shader gate"
    print(f"{gate_name}: {passed}/{len(results)} recipes passed; report: {report_path}")
    gate_passed = frontend_passed if args.skip_metal else bool(full_gate_passed)
    return 0 if gate_passed else 1


if __name__ == "__main__":
    raise SystemExit(main())
