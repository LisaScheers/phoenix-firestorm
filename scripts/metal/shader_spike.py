@dataclass
class InputSnapshot:
    """Immutable build inputs captured before any translation tool is run."""

    manifest_path: Path
    manifest_bytes: bytes
    _files: dict[Path, bytes] = field(default_factory=dict, repr=False)
    _roles: dict[Path, set[str]] = field(default_factory=dict, repr=False)
    _source_resolutions: dict[tuple[Path, int, str], Path] = field(
        default_factory=dict, repr=False
    )
    frozen: bool = False

    @staticmethod
    def _read_stable_file(path: Path, role: str) -> bytes:
        flags = os.O_RDONLY | getattr(os, "O_CLOEXEC", 0)
        flags |= getattr(os, "O_NOFOLLOW", 0)
        try:
            descriptor = os.open(path, flags)
        except OSError as error:
            raise ManifestError(
                f"cannot capture {role} input {path}: {error}"
            ) from error
        try:
            before = os.fstat(descriptor)
            if not stat.S_ISREG(before.st_mode):
                raise ManifestError(f"{role} input is not a regular file: {path}")
            chunks: list[bytes] = []
            while chunk := os.read(descriptor, 1024 * 1024):
                chunks.append(chunk)
            after = os.fstat(descriptor)
            before_identity = (
                before.st_dev,
                before.st_ino,
                before.st_size,
                before.st_mtime_ns,
                before.st_ctime_ns,
            )
            after_identity = (
                after.st_dev,
                after.st_ino,
                after.st_size,
                after.st_mtime_ns,
                after.st_ctime_ns,
            )
            contents = b"".join(chunks)
            if before_identity != after_identity or len(contents) != after.st_size:
                raise ManifestError(
                    f"{role} input changed while being captured: {path}"
                )
            current = os.stat(path, follow_symlinks=False)
            if (current.st_dev, current.st_ino) != (after.st_dev, after.st_ino):
                raise ManifestError(
                    f"{role} input path changed while being captured: {path}"
                )
            return contents
        except OSError as error:
            raise ManifestError(
                f"cannot capture {role} input {path}: {error}"
            ) from error
        finally:
            os.close(descriptor)

    @classmethod
    def capture_manifest(cls, path: Path) -> InputSnapshot:
        resolved = path.resolve()
        contents = cls._read_stable_file(resolved, "manifest")
        snapshot = cls(resolved, contents)
        snapshot._files[resolved] = contents
        snapshot._roles[resolved] = {"manifest"}
        return snapshot

    def capture(self, path: Path, role: str) -> bytes:
        resolved = path.resolve()
        if resolved in self._files:
            self._roles[resolved].add(role)
            return self._files[resolved]
        if self.frozen:
            raise ManifestError(
                f"input snapshot is frozen; uncaptured input: {resolved}"
            )
        contents = self._read_stable_file(resolved, role)
        self._files[resolved] = contents
        self._roles[resolved] = {role}
        return contents

    def text(self, path: Path, role: str) -> str:
        try:
            return self.capture(path, role).decode("utf-8")
        except UnicodeDecodeError as error:
            raise ManifestError(f"{role} input is not UTF-8: {path}") from error

    def remember_source(
        self, source_root: Path, shader_class: int, logical_path: str, path: Path
    ) -> None:
        if self.frozen:
            raise ManifestError("cannot add a source resolution to a frozen snapshot")
        key = (source_root.resolve(), shader_class, logical_path)
        self.capture(path, "shader_source")
        self._source_resolutions[key] = path.resolve()

    def resolved_source(
        self, source_root: Path, shader_class: int, logical_path: str
    ) -> Path | None:
        return self._source_resolutions.get(
            (source_root.resolve(), shader_class, logical_path)
        )

    def freeze(self) -> None:
        self.frozen = True

    def digest(self, path: Path) -> str:
        resolved = path.resolve()
        try:
            contents = self._files[resolved]
        except KeyError as error:
            raise ManifestError(f"input was not captured: {resolved}") from error
        return hashlib.sha256(contents).hexdigest()

    def captured_hashes(self) -> dict[str, str]:
        root = repository_root().resolve()

        def label(path: Path) -> str:
            return (
                str(path.relative_to(root)) if _path_within(path, root) else str(path)
            )

        return {
            label(path): hashlib.sha256(contents).hexdigest()
            for path, contents in sorted(
                self._files.items(), key=lambda item: str(item[0])
            )
        }

    def shader_hashes(self) -> dict[str, str]:
        root = repository_root().resolve()
        paths = {
            path for path, roles in self._roles.items() if "shader_source" in roles
        }
        return {
            str(path.relative_to(root)): self.digest(path)
            for path in sorted(paths, key=str)
        }


