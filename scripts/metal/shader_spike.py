def repository_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _require_string(value: object, field: str) -> str:
    if not isinstance(value, str) or not value:
        raise ManifestError(f"{field} must be a non-empty string")
    return value


def _require_shader_logical_path(value: object, field: str) -> str:
    path = _require_string(value, field)
    first_component = path.split("/", 1)[0]
    if (
        "\\" in path
        or path.startswith("/")
        or re.fullmatch(r"class[0-9]+", first_component, re.IGNORECASE) is not None
        or any(part in {"", ".", ".."} for part in path.split("/"))
    ):
        raise ManifestError(
            f"{field} must be a canonical repository-relative shader path"
        )
    return path


def _path_has_exact_spelling(root: Path, path: Path) -> bool:
    """Return whether every path component matches its directory entry exactly."""

    try:
        relative = path.relative_to(root)
    except ValueError:
        return False
    current = root
    for component in relative.parts:
        try:
            with os.scandir(current) as entries:
                if component not in {entry.name for entry in entries}:
                    return False
        except OSError:
            return False
        current /= component
    return True


def _require_exact_keys(
    value: dict[object, object], expected: set[str], field: str
) -> None:
    actual = set(value)
    if actual != expected:
        missing = sorted(expected - actual)
        unexpected = sorted(actual - expected)  # type: ignore[arg-type]
        raise ManifestError(
            f"{field} keys do not match schema; missing={missing}, unexpected={unexpected}"
        )


def _require_int(value: object, field: str, minimum: int = 0) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or value < minimum:
        raise ManifestError(f"{field} must be an integer >= {minimum}")
    return value


def _load_source_index(value: object, field: str) -> int | None:
    if value is None:
        return None
    index = _require_int(value, field)
    if index > MAX_SOURCE_INDEX:
        raise ManifestError(f"{field} exceeds the unsigned 16-bit range")
    return index


def _require_defines(value: object, field: str) -> dict[str, str]:
    if not isinstance(value, dict):
        raise ManifestError(f"{field} must map non-empty strings to strings")
    result: dict[str, str] = {}
    for key, item in value.items():
        if (
            not isinstance(key, str)
            or re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", key) is None
        ):
            raise ManifestError(f"{field} contains an invalid macro name")
        if (
            not isinstance(item, str)
            or not item
            or any(
                token in item
                for token in ("\r", "\n", "#", "\\", "//", "/*", "*/", "\0")
            )
        ):
            raise ManifestError(f"{field}.{key} contains an unsafe macro value")
        result[key] = item
    return dict(sorted(result.items()))


def _path_within(path: Path, root: Path) -> bool:
    try:
        path.relative_to(root)
    except ValueError:
        return False
    return True


def _load_source_evidence(value: object, field: str) -> tuple[SourceEvidence, ...]:
    if not isinstance(value, list) or not value:
        raise ManifestError(f"{field} must be a non-empty array")
    result: list[SourceEvidence] = []
    for index, item in enumerate(value):
        prefix = f"{field}[{index}]"
        if not isinstance(item, dict) or set(item) != {"path", "contains"}:
            raise ManifestError(f"{prefix} must contain exactly path and contains")
        result.append(
            SourceEvidence(
                path=_require_string(item.get("path"), f"{prefix}.path"),
                contains=_require_string(item.get("contains"), f"{prefix}.contains"),
            )
        )
    return tuple(result)


def _load_vertex_layouts(value: object, field: str) -> tuple[VertexLayout, ...]:
    if not isinstance(value, list) or not value:
        raise ManifestError(f"{field} must be a non-empty array")
    layouts: list[VertexLayout] = []
    seen_buffers: set[int] = set()
    seen_names: set[str] = set()
    seen_locations: set[int] = set()
    for layout_index, layout_value in enumerate(value):
        prefix = f"{field}[{layout_index}]"
        if not isinstance(layout_value, dict):
            raise ManifestError(f"{prefix} must be an object")
        _require_exact_keys(
            layout_value,
            {"buffer_index", "stride", "step_function", "attributes"},
            prefix,
        )
        buffer_index = _require_int(
            layout_value.get("buffer_index"), f"{prefix}.buffer_index"
        )
        if buffer_index > MAX_METAL_BUFFER_INDEX:
            raise ManifestError(f"{prefix}.buffer_index exceeds the Metal limit")
        if buffer_index == DEFAULT_UNIFORM_BUFFER_INDEX:
            raise ManifestError(f"{prefix}.buffer_index collides with the default UBO")
        if buffer_index in seen_buffers:
            raise ManifestError(f"{field} has duplicate buffer index {buffer_index}")
        seen_buffers.add(buffer_index)
        stride = _require_int(layout_value.get("stride"), f"{prefix}.stride", 1)
        step_function = _require_string(
            layout_value.get("step_function"), f"{prefix}.step_function"
        )
        if step_function not in {"per_vertex", "per_instance", "constant"}:
            raise ManifestError(f"{prefix}.step_function is unsupported")
        attributes_value = layout_value.get("attributes")
        if not isinstance(attributes_value, list) or not attributes_value:
            raise ManifestError(f"{prefix}.attributes must be a non-empty array")
        attributes: list[VertexAttribute] = []
        for attribute_index, attribute_value in enumerate(attributes_value):
            attr_prefix = f"{prefix}.attributes[{attribute_index}]"
            if not isinstance(attribute_value, dict):
                raise ManifestError(f"{attr_prefix} must be an object")
            _require_exact_keys(
                attribute_value, {"name", "location", "format", "offset"}, attr_prefix
            )
            name = _require_string(attribute_value.get("name"), f"{attr_prefix}.name")
            if name not in RESERVED_VERTEX_ATTRIBUTES:
                raise ManifestError(f"{attr_prefix}.name is not a reserved attribute")
            location = _require_int(
                attribute_value.get("location"), f"{attr_prefix}.location"
            )
            if location != RESERVED_VERTEX_ATTRIBUTES[name]:
                raise ManifestError(
                    f"{attr_prefix}.location does not match the Firestorm attribute contract"
                )
            if name in seen_names or location in seen_locations:
                raise ManifestError(f"{field} has a duplicate vertex attribute")
            seen_names.add(name)
            seen_locations.add(location)
            format_name = _require_string(
                attribute_value.get("format"), f"{attr_prefix}.format"
            )
            if format_name not in VERTEX_FORMATS:
                raise ManifestError(f"{attr_prefix}.format is unsupported")
            offset = _require_int(
                attribute_value.get("offset"), f"{attr_prefix}.offset"
            )
            size, _ = VERTEX_FORMATS[format_name]
            if offset + size > stride:
                raise ManifestError(f"{attr_prefix} exceeds its declared stride")
            attributes.append(
                VertexAttribute(name, location, format_name, offset, buffer_index)
            )
        layouts.append(
            VertexLayout(buffer_index, stride, step_function, tuple(attributes))
        )
    return tuple(layouts)


def _load_pipeline(
    value: object,
    prefix: str,
    vertex_contracts: dict[str, tuple[VertexLayout, ...]],
) -> PipelineSpec:
    if not isinstance(value, dict):
        raise ManifestError(f"{prefix}.pipeline must be an object")
    _require_exact_keys(
        value,
        {
            "color_formats",
            "depth_format",
            "sample_count",
            "source_evidence",
            "vertex_contract",
        },
        f"{prefix}.pipeline",
    )
    colors = value.get("color_formats")
    if not isinstance(colors, list) or not all(
        isinstance(item, str) and item in COLOR_FORMATS for item in colors
    ):
        raise ManifestError(
            f"{prefix}.pipeline.color_formats must use supported Metal formats"
        )
    if len(colors) > 8:
        raise ManifestError(f"{prefix}.pipeline.color_formats exceeds eight slots")
    depth = value.get("depth_format")
    if depth is not None and depth not in DEPTH_FORMATS:
        raise ManifestError(f"{prefix}.pipeline.depth_format is unsupported")
    contract_name = _require_string(
        value.get("vertex_contract"), f"{prefix}.pipeline.vertex_contract"
    )
    if contract_name not in vertex_contracts:
        raise ManifestError(f"{prefix}.pipeline.vertex_contract is not declared")
    return PipelineSpec(
        color_formats=tuple(colors),
        depth_format=depth,
        sample_count=_require_int(
            value.get("sample_count", 1), f"{prefix}.pipeline.sample_count", 1
        ),
        vertex_layouts=vertex_contracts[contract_name],
        source_evidence=_load_source_evidence(
            value.get("source_evidence"), f"{prefix}.pipeline.source_evidence"
        ),
    )


def _load_reflection_requirements(
    value: object, prefix: str
) -> dict[str, tuple[ReflectionRequirement, ...]]:
    if not isinstance(value, dict) or not value:
        raise ManifestError(f"{prefix}.required_reflection must be a non-empty object")
    if not set(value).issubset(STAGE_SUFFIX):
        raise ManifestError(f"{prefix}.required_reflection has an unsupported stage")

    result: dict[str, tuple[ReflectionRequirement, ...]] = {}
    for stage, requirements_value in value.items():
        if not isinstance(requirements_value, list) or not requirements_value:
            raise ManifestError(
                f"{prefix}.required_reflection.{stage} must be a non-empty array"
            )
        requirements: list[ReflectionRequirement] = []
        for index, requirement_value in enumerate(requirements_value):
            requirement_prefix = f"{prefix}.required_reflection.{stage}[{index}]"
            if not isinstance(requirement_value, dict):
                raise ManifestError(f"{requirement_prefix} must be an object")
            allowed_keys = {"group", "name"}
            if "type" in requirement_value:
                allowed_keys.add("type")
            _require_exact_keys(requirement_value, allowed_keys, requirement_prefix)
            group = _require_string(
                requirement_value.get("group"), f"{requirement_prefix}.group"
            )
            if group not in REFLECTION_GROUPS:
                raise ManifestError(
                    f"{requirement_prefix}.group must be one of "
                    + ", ".join(sorted(REFLECTION_GROUPS))
                )
            resource_type = requirement_value.get("type")
            if resource_type is not None and not isinstance(resource_type, str):
                raise ManifestError(
                    f"{requirement_prefix}.type must be a string when present"
                )
            requirements.append(
                ReflectionRequirement(
                    group=group,
                    name=_require_string(
                        requirement_value.get("name"), f"{requirement_prefix}.name"
                    ),
                    resource_type=resource_type,
                )
            )
        result[stage] = tuple(requirements)
    return result


def _load_comparison_sample_counts(
    value: object,
    prefix: str,
    reflection: dict[str, tuple[ReflectionRequirement, ...]],
) -> dict[str, int]:
    required_stages = {
        stage
        for stage, requirements in reflection.items()
        if any(
            requirement.resource_type is not None
            and requirement.resource_type.endswith("Shadow")
            for requirement in requirements
        )
    }
    field = f"{prefix}.comparison_sample_counts"
    if value is None:
        if required_stages:
            raise ManifestError(
                f"{field} must cover shadow-sampling stages {sorted(required_stages)}"
            )
        return {}
    if not isinstance(value, dict):
        raise ManifestError(f"{field} must be an object")
    _require_exact_keys(value, required_stages, field)
    return {
        stage: _require_int(count, f"{field}.{stage}", 1)
        for stage, count in value.items()
    }


def _load_settings(
    value: object, field: str, *, require_all: bool
) -> dict[str, bool | int]:
    if not isinstance(value, dict):
        raise ManifestError(f"{field} must be an object")
    actual = set(value)
    expected = set(BASELINE_SETTING_TYPES)
    if require_all and actual != expected:
        raise ManifestError(
            f"{field} must contain exactly {', '.join(sorted(expected))}"
        )
    if not actual.issubset(expected):
        raise ManifestError(f"{field} contains an unsupported setting")
    result: dict[str, bool | int] = {}
    for name, item in value.items():
        expected_type = BASELINE_SETTING_TYPES[name]
        if type(item) is not expected_type:
            raise ManifestError(f"{field}.{name} has the wrong value type")
        if expected_type is int and int(item) < 0:
            raise ManifestError(f"{field}.{name} must be non-negative")
        if expected_type is int and int(item) > MAX_SELECTION_SETTING:
            raise ManifestError(f"{field}.{name} exceeds the signed 32-bit range")
        result[name] = item
    return dict(sorted(result.items()))


def _validate_settings_xml(
    settings: dict[str, bool | int], root: Path, inputs: InputSnapshot
) -> None:
    path = root / "indra/newview/app_settings/settings.xml"
    try:
        document = ET.fromstring(inputs.capture(path, "settings_contract"))
    except ET.ParseError as error:
        raise ManifestError(f"cannot parse settings contract: {error}") from error
    top = document.find("map")
    if top is None:
        raise ManifestError("settings.xml has no top-level map")
    children = list(top)
    declared_types: dict[str, str] = {}
    for index in range(0, len(children) - 1, 2):
        key, value = children[index : index + 2]
        if key.tag != "key" or not key.text or value.tag != "map":
            continue
        value_children = list(value)
        for inner_index in range(0, len(value_children) - 1, 2):
            inner_key, inner_value = value_children[inner_index : inner_index + 2]
            if inner_key.tag == "key" and inner_key.text == "Type" and inner_value.text:
                declared_types[key.text] = inner_value.text
                break
    for name, value in settings.items():
        expected = "Boolean" if isinstance(value, bool) else None
        actual = declared_types.get(name)
        if expected is not None and actual != expected:
            raise ManifestError(
                f"baseline setting {name} is not Boolean in settings.xml"
            )
        if expected is None and actual not in {"S32", "U32"}:
            raise ManifestError(
                f"baseline setting {name} is not integer in settings.xml"
            )


def program_selection_key(recipe: ProgramRecipe) -> tuple[str, int | None, int]:
    """Return the source-level identity used to select one bundled program."""

    return recipe.source_symbol, recipe.source_index, recipe.shader_class


def program_selection(recipe: ProgramRecipe) -> dict[str, object]:
    """Render the exact typed selector consumed by the runtime artifact catalog."""

    if recipe.recipe_kind not in BUNDLED_RECIPE_KINDS:
        raise ManifestError(f"{recipe.program_id} is not a bundled runtime program")
    boolean_settings = [
        {"name": name, "value": value}
        for name, value in sorted(recipe.settings_overrides.items())
        if type(value) is bool
    ]
    integer_settings = [
        {"name": name, "value": value}
        for name, value in sorted(recipe.settings_overrides.items())
        if type(value) is int
    ]
    return {
        "source_symbol": recipe.source_symbol,
        "source_index": recipe.source_index,
        "shader_class": recipe.shader_class,
        "boolean_settings": boolean_settings,
        "integer_settings": integer_settings,
    }


def _validate_program_selection_contracts(programs: list[ProgramRecipe]) -> None:
    by_id = {recipe.program_id: recipe for recipe in programs}
    required_variants = REQUIRED_FXAA_VARIANT_IDS | REQUIRED_SMAA_VARIANT_IDS
    missing_variants = sorted(required_variants - set(by_id))
    if missing_variants:
        raise ManifestError(
            f"the antialiasing variant contract is incomplete: "
            f"{', '.join(missing_variants)}"
        )

    indexed_symbols = {"gFXAAProgram"} | {
        contract[0] for contract in SMAA_PASS_CONTRACT.values()
    }
    keys: dict[tuple[str, int | None, int], str] = {}
    for recipe in programs:
        if recipe.recipe_kind not in BUNDLED_RECIPE_KINDS:
            continue
        if recipe.source_symbol == "gFXAAProgram":
            if recipe.program_id not in REQUIRED_FXAA_VARIANT_IDS:
                raise ManifestError(
                    f"unexpected bundled gFXAAProgram variant: {recipe.program_id}"
                )
        elif recipe.source_symbol in indexed_symbols:
            if recipe.program_id not in REQUIRED_SMAA_VARIANT_IDS:
                raise ManifestError(
                    f"unexpected bundled SMAA source variant: {recipe.program_id}"
                )
        elif recipe.source_index is not None:
            raise ManifestError(
                f"{recipe.program_id} scalar source_symbol requires a null source_index"
            )
        key = program_selection_key(recipe)
        if previous := keys.get(key):
            raise ManifestError(
                f"bundled program selection key collides: {previous} and "
                f"{recipe.program_id}"
            )
        keys[key] = recipe.program_id

    ultra = by_id["fxaa"]
    for program_id, (
        recipe_kind,
        source_index,
        preset,
    ) in FXAA_VARIANT_CONTRACT.items():
        recipe = by_id[program_id]
        if (
            recipe.family != "SMAA or FXAA"
            or recipe.recipe_kind != recipe_kind
            or recipe.source_symbol != "gFXAAProgram"
            or recipe.source_index != source_index
            or recipe.shader_class != 3
            or recipe.settings_overrides
            != {"RenderFSAASamples": source_index, "RenderFSAAType": 1}
            or recipe.defines
            != {
                "FXAA_GLSL_400": "1",
                "FXAA_NO_DEPTH_WRITE": "1",
                "FXAA_QUALITY__PRESET": preset,
            }
        ):
            raise ManifestError(f"{program_id} does not match the exact FXAA mapping")
        if (
            recipe.source_reference != ultra.source_reference
            or recipe.indexed_texture_channels != ultra.indexed_texture_channels
            or recipe.stages != ultra.stages
            or recipe.stage_program_counts != ultra.stage_program_counts
            or recipe.required_reflection != ultra.required_reflection
            or recipe.comparison_sample_counts != ultra.comparison_sample_counts
            or recipe.pipeline != ultra.pipeline
            or recipe.semantic_parity != ultra.semantic_parity
        ):
            raise ManifestError(
                f"{program_id} does not share the FXAA runtime recipe contract"
            )

    deferred_vertex_features = (
        "windlight/atmosphericsVarsV.glsl",
        "deferred/textureUtilV.glsl",
        "objects/nonindexedTextureV.glsl",
    )
    deferred_fragment_features = (
        "deferred/globalF.glsl",
        "environment/srgbF.glsl",
        "windlight/atmosphericsVarsF.glsl",
        "deferred/deferredUtil.glsl",
        "windlight/gammaF.glsl",
        "windlight/atmosphericsFuncs.glsl",
        "windlight/atmosphericsF.glsl",
    )
    reflection_names = {
        "edge": {"diffuseRect"},
        "weights": {"edgesTex", "areaTex", "searchTex"},
        "neighborhood": {"diffuseRect", "blendTex"},
    }
    pipeline_evidence = {
        "edge": (
            SourceEvidence(
                "indra/newview/pipeline.cpp",
                "if (!mFXAAMap.allocate(resX, resY, GL_RGBA)) return false;",
            ),
            SourceEvidence(
                "indra/newview/pipeline.cpp",
                "LLGLSLShader& edge_shader = gSMAAEdgeDetectProgram[fsaa_quality];",
            ),
        ),
        "weights": (
            SourceEvidence(
                "indra/newview/pipeline.cpp",
                "if (!mSMAABlendBuffer.allocate(resX, resY, GL_RGBA, false)) return false;",
            ),
            SourceEvidence(
                "indra/newview/pipeline.cpp",
                "LLGLSLShader& blend_weights_shader = gSMAABlendWeightsProgram[fsaa_quality];",
            ),
        ),
        "neighborhood": (
            SourceEvidence(
                "indra/newview/pipeline.cpp",
                "mPostPongMap.allocate(resX, resY, GL_RGBA);",
            ),
            SourceEvidence(
                "indra/newview/pipeline.cpp",
                "LLGLSLShader& blend_shader = gSMAANeighborhoodBlendProgram[fsaa_quality];",
            ),
        ),
    }
    for program_id, (
        source_symbol,
        source_index,
        preset,
        vertex_source,
        fragment_source,
        source_reference,
    ) in SMAA_VARIANT_CONTRACT.items():
        recipe = by_id[program_id]
        pass_name = program_id.removeprefix("smaa_").rsplit("_", 1)[0]
        expected_defines = {
            "SMAA_GLSL_4": "1",
            "SMAA_PREDICATION": "0",
            "SMAA_REPROJECTION": "0",
            preset: "1",
        }
        if (
            recipe.family != "SMAA or FXAA"
            or recipe.recipe_kind != "runtime_variant"
            or recipe.source_reference != source_reference
            or recipe.source_symbol != source_symbol
            or recipe.source_index != source_index
            or recipe.shader_class != 3
            or recipe.settings_overrides
            != {"RenderFSAASamples": source_index, "RenderFSAAType": 2}
            or recipe.defines != expected_defines
            or recipe.indexed_texture_channels != 0
            or recipe.stages
            != {
                "vertex": (
                    vertex_source,
                    "deferred/SMAA.glsl",
                    *deferred_vertex_features,
                ),
                "fragment": (
                    fragment_source,
                    "deferred/SMAA.glsl",
                    *deferred_fragment_features,
                ),
            }
            or recipe.stage_program_counts != {"vertex": 2, "fragment": 2}
            or recipe.comparison_sample_counts
            or recipe.semantic_parity != "not_run"
        ):
            raise ManifestError(f"{program_id} does not match the exact SMAA mapping")
        fragment_reflection = recipe.required_reflection.get("fragment", ())
        if (
            set(recipe.required_reflection) != {"fragment"}
            or {
                requirement.name
                for requirement in fragment_reflection
                if requirement.group == "textures"
                and requirement.resource_type == "sampler2D"
            }
            != reflection_names[pass_name]
            or len(fragment_reflection) != len(reflection_names[pass_name])
            or recipe.pipeline.color_formats != ("rgba8unorm",)
            or recipe.pipeline.depth_format is not None
            or recipe.pipeline.sample_count != 1
            or len(recipe.pipeline.vertex_layouts) != 1
            or recipe.pipeline.vertex_layouts[0].buffer_index != 16
            or recipe.pipeline.source_evidence != pipeline_evidence[pass_name]
        ):
            raise ManifestError(
                f"{program_id} does not match the exact SMAA pipeline contract"
            )


def _validate_contract_sources(
    value: object, root: Path, inputs: InputSnapshot
) -> None:
    if not isinstance(value, list) or not value:
        raise ManifestError("source_contracts must be a non-empty array")
    seen: set[str] = set()
    for index, item in enumerate(value):
        prefix = f"source_contracts[{index}]"
        if not isinstance(item, dict) or set(item) != {"path", "sha256"}:
            raise ManifestError(f"{prefix} must contain exactly path and sha256")
        relative = _require_string(item.get("path"), f"{prefix}.path")
        expected_hash = _require_string(item.get("sha256"), f"{prefix}.sha256")
        if re.fullmatch(r"[0-9a-f]{64}", expected_hash) is None:
            raise ManifestError(f"{prefix}.sha256 must be lowercase SHA-256")
        if relative in seen:
            raise ManifestError(f"duplicate source contract: {relative}")
        seen.add(relative)
        candidate = (root / relative).resolve()
        if not _path_within(candidate, root) or not candidate.is_file():
            raise ManifestError(f"{prefix}.path is not a repository file")
        actual_hash = hashlib.sha256(
            inputs.capture(candidate, "source_contract")
        ).hexdigest()
        if actual_hash != expected_hash:
            raise ManifestError(f"source contract is stale: {relative}")


def load_manifest(
    path: Path, inputs: InputSnapshot | None = None
) -> tuple[Path, list[ProgramRecipe]]:
    inputs = inputs or InputSnapshot.capture_manifest(path)
    if path.resolve() != inputs.manifest_path:
        raise ManifestError("manifest path does not match its captured byte snapshot")
    try:
        document = json.loads(inputs.manifest_bytes.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ManifestError(f"cannot read {path}: {error}") from error
    if not isinstance(document, dict):
        raise ManifestError("manifest root must be an object")
    _require_exact_keys(
        document,
        {
            "baseline_commit",
            "baseline_settings",
            "feature_classes",
            "global_defines",
            "glsl_version",
            "programs",
            "required_families",
            "schema",
            "source_contracts",
            "source_root",
            "vertex_contracts",
            "vertex_streams",
        },
        "manifest",
    )
    if document.get("schema") != 5:
        raise ManifestError("manifest schema must be 5")

    root = repository_root().resolve()
    source_root_value = _require_string(document.get("source_root"), "source_root")
    source_root = (root / source_root_value).resolve()
    if not _path_within(source_root, root) or not source_root.is_dir():
        raise ManifestError(
            "source_root must resolve to a directory inside the repository"
        )

    glsl_version = _require_int(document.get("glsl_version"), "glsl_version", 1)
    if glsl_version != GLSL_VERSION:
        raise ManifestError(f"glsl_version must be {GLSL_VERSION}")
    baseline_commit = _require_string(
        document.get("baseline_commit"), "baseline_commit"
    )
    if re.fullmatch(r"[0-9a-f]{40}", baseline_commit) is None:
        raise ManifestError("baseline_commit must be a full lowercase Git object ID")
    baseline_settings = _load_settings(
        document.get("baseline_settings"), "baseline_settings", require_all=True
    )
    if baseline_settings["RenderFSAASamples"] > 3:
        raise ManifestError("baseline RenderFSAASamples must select an index in [0, 3]")
    _validate_settings_xml(baseline_settings, root, inputs)
    global_defines = _require_defines(
        document.get("global_defines", {}), "global_defines"
    )
    expected_global_defines = {
        "REFMAP_LEVEL": str(baseline_settings["RenderReflectionProbeLevel"]),
        "REF_SAMPLE_COUNT": "32",
    }
    if not baseline_settings["RenderReflectionsEnabled"]:
        expected_global_defines = {}
    if global_defines != expected_global_defines:
        raise ManifestError("global_defines do not match baseline reflection settings")

    required_families = document.get("required_families")
    if (
        not isinstance(required_families, list)
        or not all(isinstance(item, str) for item in required_families)
        or set(required_families) != REQUIRED_FAMILIES
        or len(required_families) != len(REQUIRED_FAMILIES)
    ):
        raise ManifestError(
            "required_families must contain the exact ten-family contract"
        )
    _validate_contract_sources(document.get("source_contracts"), root, inputs)
    feature_classes_value = document.get("feature_classes")
    if not isinstance(feature_classes_value, dict) or not feature_classes_value:
        raise ManifestError("feature_classes must be a non-empty object")
    feature_classes = {
        _require_shader_logical_path(path_value, "feature_classes key"): _require_int(
            class_value, f"feature_classes.{path_value}", 1
        )
        for path_value, class_value in feature_classes_value.items()
    }
    unsupported_feature_classes = {
        path_value: class_value
        for path_value, class_value in feature_classes.items()
        if class_value > MAX_SHADER_CLASS
    }
    if unsupported_feature_classes:
        raise ManifestError(
            "feature_classes values must be in the supported source range [1, 3]"
        )
    vertex_streams_value = document.get("vertex_streams")
    if not isinstance(vertex_streams_value, dict) or not vertex_streams_value:
        raise ManifestError("vertex_streams must be a non-empty object")
    vertex_streams = {
        _require_string(name, "vertex_streams key"): _load_vertex_layouts(
            [stream], f"vertex_streams.{name}"
        )[0]
        for name, stream in vertex_streams_value.items()
    }
    vertex_contracts_value = document.get("vertex_contracts")
    if not isinstance(vertex_contracts_value, dict) or not vertex_contracts_value:
        raise ManifestError("vertex_contracts must be a non-empty object")
    vertex_contracts: dict[str, tuple[VertexLayout, ...]] = {}
    for name, contract in vertex_contracts_value.items():
        contract_name = _require_string(name, "vertex_contracts key")
        if (
            not isinstance(contract, list)
            or not contract
            or not all(isinstance(item, str) and item for item in contract)
        ):
            raise ManifestError(f"vertex_contracts.{contract_name} must list streams")
        if len(contract) != len(set(contract)):
            raise ManifestError(f"vertex_contracts.{contract_name} repeats a stream")
        try:
            layouts = tuple(vertex_streams[item] for item in contract)
        except KeyError as error:
            raise ManifestError(
                f"vertex_contracts.{contract_name} uses an unknown stream"
            ) from error
        buffers = [item.buffer_index for item in layouts]
        names = [attribute.name for item in layouts for attribute in item.attributes]
        locations = [
            attribute.location for item in layouts for attribute in item.attributes
        ]
        if len(buffers) != len(set(buffers)):
            raise ManifestError(
                f"vertex_contracts.{contract_name} collides buffer streams"
            )
        if len(names) != len(set(names)) or len(locations) != len(set(locations)):
            raise ManifestError(f"vertex_contracts.{contract_name} repeats attributes")
        vertex_contracts[contract_name] = layouts

    programs_value = document.get("programs")
    if not isinstance(programs_value, list) or not programs_value:
        raise ManifestError("programs must be a non-empty array")

    programs: list[ProgramRecipe] = []
    seen_ids: set[str] = set()
    for index, value in enumerate(programs_value):
        prefix = f"programs[{index}]"
        if not isinstance(value, dict):
            raise ManifestError(f"{prefix} must be an object")
        program_keys = {
            "defines",
            "family",
            "id",
            "indexed_texture_channels",
            "pipeline",
            "recipe_kind",
            "required_reflection",
            "semantic_parity",
            "settings_overrides",
            "shader_class",
            "source_reference",
            "source_symbol",
            "stages",
        }
        if "comparison_sample_counts" in value:
            program_keys.add("comparison_sample_counts")
        if "source_index" in value:
            program_keys.add("source_index")
        _require_exact_keys(value, program_keys, prefix)
        program_id = _require_string(value.get("id"), f"{prefix}.id")
        if not re.fullmatch(r"[a-z][a-z0-9_]*", program_id):
            raise ManifestError(f"{prefix}.id must be a stable snake_case identifier")
        if program_id in seen_ids:
            raise ManifestError(f"duplicate program id: {program_id}")
        seen_ids.add(program_id)

        recipe_kind = _require_string(value.get("recipe_kind"), f"{prefix}.recipe_kind")
        if recipe_kind not in RECIPE_KINDS:
            raise ManifestError(
                f"{prefix}.recipe_kind must be one of {', '.join(sorted(RECIPE_KINDS))}"
            )
        bundled = recipe_kind in BUNDLED_RECIPE_KINDS
        if bundled and "source_index" not in value:
            raise ManifestError(
                f"{prefix}.source_index is required for bundled recipes"
            )
        if not bundled and "source_index" in value:
            raise ManifestError(
                f"{prefix}.source_index is only valid for bundled recipes"
            )
        source_index = _load_source_index(
            value.get("source_index"), f"{prefix}.source_index"
        )
        source_symbol = _require_string(
            value.get("source_symbol"), f"{prefix}.source_symbol"
        )
        if bundled and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", source_symbol) is None:
            raise ManifestError(
                f"{prefix}.source_symbol must be a C identifier for bundled recipes"
            )
        shader_class = _require_int(
            value.get("shader_class"), f"{prefix}.shader_class", 1
        )
        if shader_class > MAX_SHADER_CLASS:
            raise ManifestError(
                f"{prefix}.shader_class must be in the supported source range [1, 3]"
            )

        settings_overrides = _load_settings(
            value.get("settings_overrides", {}),
            f"{prefix}.settings_overrides",
            require_all=False,
        )
        effective_settings = baseline_settings | settings_overrides
        if effective_settings["RenderFSAASamples"] > 3:
            raise ManifestError(
                f"{program_id} RenderFSAASamples must select an index in [0, 3]"
            )
        if (
            program_id == "shadow_alpha_mask"
            and effective_settings["RenderShadowDetail"] < 1
        ):
            raise ManifestError("shadow_alpha_mask must enable RenderShadowDetail")
        if program_id.startswith("fxaa") and effective_settings["RenderFSAAType"] < 1:
            raise ManifestError(f"{program_id} must enable RenderFSAAType")

        stages_value = value.get("stages")
        if not isinstance(stages_value, dict) or set(stages_value) != set(STAGE_SUFFIX):
            raise ManifestError(f"{prefix}.stages must contain vertex and fragment")
        stages: dict[str, tuple[str, ...]] = {}
        stage_program_counts: dict[str, int] = {}
        for stage in STAGE_SUFFIX:
            stage_value = stages_value.get(stage)
            if not isinstance(stage_value, dict):
                raise ManifestError(f"{prefix}.stages.{stage} must be an object")
            _require_exact_keys(
                stage_value,
                {"program", "features"},
                f"{prefix}.stages.{stage}",
            )
            program_sources = stage_value.get("program")
            if (
                not isinstance(program_sources, list)
                or not program_sources
                or not all(
                    isinstance(source, str) and source for source in program_sources
                )
            ):
                raise ManifestError(
                    f"{prefix}.stages.{stage}.program must be a non-empty string array"
                )
            feature_sources = stage_value.get("features")
            if not isinstance(feature_sources, list) or not all(
                isinstance(source, str) and source for source in feature_sources
            ):
                raise ManifestError(
                    f"{prefix}.stages.{stage}.features must be a string array"
                )
            program_sources = [
                _require_shader_logical_path(source, f"{prefix}.stages.{stage}.program")
                for source in program_sources
            ]
            feature_sources = [
                _require_shader_logical_path(
                    source, f"{prefix}.stages.{stage}.features"
                )
                for source in feature_sources
            ]
            sources = [*program_sources, *feature_sources]
            if len(sources) != len(set(sources)):
                raise ManifestError(
                    f"{prefix}.stages.{stage} contains duplicate sources across roles"
                )
            for feature_source in feature_sources:
                if feature_source not in feature_classes:
                    raise ManifestError(
                        f"{prefix}.stages.{stage} feature {feature_source!r} "
                        "has no declared baseline class"
                    )
            physical_sources: dict[tuple[int, int], str] = {}
            for source_position, source in enumerate(sources):
                source_class = (
                    shader_class
                    if source_position < len(program_sources)
                    else feature_classes[source]
                )
                resolved = resolve_source(source_root, source_class, source, inputs)
                source_stat = resolved.stat()
                identity = (source_stat.st_dev, source_stat.st_ino)
                if previous := physical_sources.get(identity):
                    raise ManifestError(
                        f"{prefix}.stages.{stage} contains duplicate physical shader "
                        f"sources: {previous!r} and {source!r}"
                    )
                physical_sources[identity] = source
            stages[stage] = tuple(sources)
            stage_program_counts[stage] = len(program_sources)

        defines = _require_defines(value.get("defines", {}), f"{prefix}.defines")
        indexed_texture_channels = _require_int(
            value.get("indexed_texture_channels", 0),
            f"{prefix}.indexed_texture_channels",
        )
        if indexed_texture_channels > MAX_METAL_SAMPLER_INDEX + 1:
            raise ManifestError(
                f"{prefix}.indexed_texture_channels exceeds Metal limits"
            )
        if program_id == "avatar_skinning":
            expected_cloth = "1" if baseline_settings["RenderAvatarCloth"] else "0"
            if defines.get("AVATAR_CLOTH") != expected_cloth:
                raise ManifestError(
                    "avatar_skinning AVATAR_CLOTH disagrees with settings"
                )
        if not baseline_settings["RenderMirrors"] and "HERO_PROBES" in global_defines:
            raise ManifestError(
                "HERO_PROBES must be absent when RenderMirrors is false"
            )
        semantic_parity = _require_string(
            value.get("semantic_parity", "not_run"), f"{prefix}.semantic_parity"
        )
        if semantic_parity not in {"not_run", "cpu_runtime_layout_open"}:
            raise ManifestError(f"{prefix}.semantic_parity has an unsupported state")
        if (
            program_id == "avatar_skinning"
            and semantic_parity != "cpu_runtime_layout_open"
        ):
            raise ManifestError(
                "avatar_skinning CPU runtime layout parity must remain open"
            )

        effective_global_defines = dict(global_defines)
        if effective_settings["RenderShadowDetail"] >= 1:
            effective_global_defines["SUN_SHADOW"] = "1"
        if effective_settings["RenderShadowDetail"] >= 2:
            effective_global_defines["SPOT_SHADOW"] = "1"

        required_reflection = _load_reflection_requirements(
            value.get("required_reflection"), prefix
        )

        programs.append(
            ProgramRecipe(
                program_id=program_id,
                family=_require_string(value.get("family"), f"{prefix}.family"),
                recipe_kind=recipe_kind,
                source_reference=_require_string(
                    value.get("source_reference"), f"{prefix}.source_reference"
                ),
                source_symbol=source_symbol,
                source_index=source_index,
                shader_class=shader_class,
                defines=defines,
                global_defines=effective_global_defines,
                glsl_version=glsl_version,
                baseline_commit=baseline_commit,
                baseline_settings=baseline_settings,
                settings_overrides=settings_overrides,
                feature_classes=feature_classes,
                indexed_texture_channels=indexed_texture_channels,
                stages=stages,
                stage_program_counts=stage_program_counts,
                required_reflection=required_reflection,
                comparison_sample_counts=_load_comparison_sample_counts(
                    value.get("comparison_sample_counts"), prefix, required_reflection
                ),
                pipeline=_load_pipeline(
                    value.get("pipeline"), prefix, vertex_contracts
                ),
                semantic_parity=semantic_parity,
                input_snapshot=inputs,
            )
        )
    _validate_program_selection_contracts(programs)
    return source_root, programs


def resolve_source(
    source_root: Path,
    shader_class: int,
    logical_path: str,
    inputs: InputSnapshot | None = None,
) -> Path:
    logical = Path(logical_path)
    if logical.is_absolute() or ".." in logical.parts:
        raise ManifestError(f"shader source escapes source_root: {logical_path}")
    root = source_root.resolve()
    if inputs is not None:
        captured = inputs.resolved_source(root, shader_class, logical_path)
        if captured is not None:
            return captured
        if inputs.frozen:
            raise ManifestError(
                f"source was not resolved before input snapshot freeze: {logical_path}"
            )
    for candidate_class in range(shader_class, 0, -1):
        unresolved = root / f"class{candidate_class}" / logical
        candidate = unresolved.resolve()
        if not _path_within(candidate, root):
            raise ManifestError(f"shader source escapes source_root: {logical_path}")
        if candidate.is_file() and _path_has_exact_spelling(root, unresolved):
            if inputs is not None:
                inputs.remember_source(root, shader_class, logical_path, candidate)
            return candidate
    unresolved = root / logical
    candidate = unresolved.resolve()
    if (
        _path_within(candidate, root)
        and candidate.is_file()
        and _path_has_exact_spelling(root, unresolved)
    ):
        if inputs is not None:
            inputs.remember_source(root, shader_class, logical_path, candidate)
        return candidate
    raise ManifestError(
        f"cannot resolve class{shader_class} shader source {logical_path} under {root}"
    )


def _validate_source_reference(recipe: ProgramRecipe, inputs: InputSnapshot) -> None:
    match = re.fullmatch(r"([^:]+):(\d+)", recipe.source_reference)
    if match is None:
        raise ManifestError(
            f"{recipe.program_id} source_reference must be a repository path and line"
        )
    relative, line_value = match.groups()
    path = (repository_root() / relative).resolve()
    root = repository_root().resolve()
    if not _path_within(path, root) or not path.is_file():
        raise ManifestError(f"{recipe.program_id} source_reference path is invalid")
    lines = inputs.text(path, "source_reference").splitlines()
    line = int(line_value)
    if line < 1 or line > len(lines):
        raise ManifestError(f"{recipe.program_id} source_reference line is invalid")
    nearby = "\n".join(lines[max(0, line - 3) : min(len(lines), line + 3)])
    if recipe.source_symbol not in nearby:
        raise ManifestError(
            f"{recipe.program_id} source symbol {recipe.source_symbol!r} "
            "is not near its declared reference"
        )


def indexed_texture_preamble(channel_count: int) -> str:
    if channel_count == 0:
        return ""
    declarations = "\n".join(
        f"uniform sampler2D tex{channel};" for channel in range(channel_count)
    )
    if channel_count == 1:
        lookup = "return texture(tex0, texcoord);"
        varying = ""
    else:
        varying = "flat in int vary_texture_index;"
        cases = "\n".join(
            f"        case {channel}: return texture(tex{channel}, texcoord);"
            for channel in range(channel_count)
        )
        lookup = (
            "switch (vary_texture_index)\n"
            "    {\n"
            f"{cases}\n"
            "    }\n"
            "    return vec4(1.0, 0.0, 1.0, 1.0);"
        )
    return (
        "#define HAS_DIFFUSE_LOOKUP 1\n"
        f"{declarations}\n"
        f"{varying}\n"
        "vec4 diffuseLookup(vec2 texcoord)\n"
        "{\n"
        f"    {lookup}\n"
        "}\n"
    )


def shader_preamble(recipe: ProgramRecipe, stage: str, is_feature: bool) -> str:
    stage_define = "VERTEX_SHADER" if stage == "vertex" else "FRAGMENT_SHADER"
    selected_defines = recipe.global_defines if is_feature else recipe.defines
    defines = "\n".join(
        f"#define {name} {value}" for name, value in selected_defines.items()
    )
    indexed = (
        indexed_texture_preamble(recipe.indexed_texture_channels)
        if stage == "fragment" and not is_feature
        else ""
    )
    return (
        "#extension GL_ARB_shading_language_420pack : enable\n"
        f"#define {stage_define} 1\n"
        "#define GBUFFER_FLAG_SKIP_ATMOS 0.0\n"
        "#define GBUFFER_FLAG_HAS_ATMOS 0.34\n"
        "#define GBUFFER_FLAG_HAS_PBR 0.67\n"
        "#define GBUFFER_FLAG_HAS_HDRI 1.0\n"
        "#define GET_GBUFFER_FLAG(data, flag) (abs((data) - (flag)) < 0.1)\n"
        f"{defines}\n"
        f"{indexed}"
        "struct GBufferInfo { vec4 albedo; vec4 specular; vec3 normal; "
        "vec4 emissive; float gbufferFlag; float envIntensity; };\n"
    )


def assemble_shader_source(
    source_text: str, preamble: str, glsl_version: int, source_label: str
) -> str:
    marker = "[EXTRA_CODE_HERE]"
    lines = source_text.splitlines(keepends=True)
    marker_lines = [index for index, line in enumerate(lines) if marker in line]
    marker_count = source_text.count(marker)
    if marker_count > 1:
        raise ManifestError(
            f"{source_label} contains {marker_count} literal {marker} markers"
        )
    injected = preamble.rstrip() + "\n"
    if marker_count == 1:
        marker_line = marker_lines[0]
        source_text = (
            "".join(lines[:marker_line]) + injected + "".join(lines[marker_line + 1 :])
        )
        body = f"// source object: {source_label}\n{source_text}"
    else:
        body = f"{injected}// source object: {source_label}\n{source_text}"
    return f"#version {glsl_version} core\n{body}"


def write_shader_objects(
    source_root: Path,
    recipe: ProgramRecipe,
    stage: str,
    program_root: Path,
) -> list[Path]:
    suffix = STAGE_SUFFIX[stage]
    object_root = program_root / "objects" / stage
    object_root.mkdir(parents=True, exist_ok=True)
    wrappers: list[Path] = []
    for index, logical_path in enumerate(recipe.stages[stage]):
        is_feature = index >= recipe.stage_program_counts[stage]
        shader_class = (
            recipe.feature_classes[logical_path] if is_feature else recipe.shader_class
        )
        source_path = resolve_source(
            source_root, shader_class, logical_path, recipe.input_snapshot
        )
        wrapper = object_root / f"{index:02d}-{Path(logical_path).stem}.{suffix}"
        relative = source_path.relative_to(repository_root())
        source_text = recipe.input_snapshot.text(source_path, "shader_source")
        wrapper.write_text(
            assemble_shader_source(
                source_text,
                shader_preamble(recipe, stage, is_feature),
                recipe.glsl_version,
                str(relative),
            ),
            encoding="utf-8",
        )
        wrappers.append(wrapper)
    return wrappers


